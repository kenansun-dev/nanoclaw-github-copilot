#!/usr/bin/env node
/**
 * write-build-info.mjs — emit src/build-info.ts with git commit + build time.
 *
 * Runs as `prebuild` so `npm run build` always produces a fresh
 * `dist/build-info.js` that the runtime imports. The generated `.ts` file
 * is gitignored so it never pollutes diffs.
 *
 * Fallbacks:
 *   - No `.git/` (e.g. tarball install in container) → COMMIT='dev'
 *   - `git` not on PATH                              → COMMIT='dev'
 *   - Any other failure                              → COMMIT='dev'
 *
 * No imports beyond node stdlib so this works in pristine sandboxes.
 */
import { execSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT = join(ROOT, 'src', 'build-info.ts');

let commit = 'dev';
try {
  if (existsSync(join(ROOT, '.git'))) {
    commit = execSync('git rev-parse --short HEAD', {
      cwd: ROOT,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim() || 'dev';
  }
} catch {
  /* keep 'dev' */
}

const buildTime = new Date().toISOString();

const body = `/* AUTO-GENERATED by scripts/write-build-info.mjs — do not edit. */
export const COMMIT: string = ${JSON.stringify(commit)};
export const BUILD_TIME: string = ${JSON.stringify(buildTime)};
`;

writeFileSync(OUT, body);
console.log(`[build-info] commit=${commit} time=${buildTime} → ${OUT}`);
